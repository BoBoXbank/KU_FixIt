from flask import Flask
from user_routes import user_bp
from admin_routes import admin_bp
from technician_routes import technician_bp
import os
from dotenv import load_dotenv
from datetime import datetime, timedelta

# ==============================================================================
# ส่วนที่ 1: การโหลดตัวแปรแวดล้อม (ENVIRONMENT VARIABLES)
# หน้าที่: โหลดค่าการตั้งค่าจากไฟล์ .env (เช่น Secret Key หรือการตั้งค่า Database)
# ==============================================================================
load_dotenv()

# ==============================================================================
# ส่วนที่ 2: การสร้างและตั้งค่าแอปพลิเคชันหลัก (APP INITIALIZATION)
# หน้าที่: สร้างอินสแตนซ์ของ Flask และตั้งค่า Secret Key สำหรับรักษาความปลอดภัยของ Session
# ==============================================================================
app = Flask(__name__)
app.secret_key = os.getenv("SECRET_KEY", "KU_Super_Secret_Key_2026")

# ==============================================================================
# ส่วนที่ 3: ตัวกรองเทมเพลตแบบกำหนดเอง (CUSTOM TEMPLATE FILTER)
# หน้าที่: สร้างฟิลเตอร์ชื่อ 'thaitime' สำหรับแปลงข้อมูลเวลาให้เป็นรูปแบบ วัน/เดือน/ปี ชั่วโมง:นาที
# ใช้งานในไฟล์: ไฟล์ HTML ต่างๆ ที่ต้องแสดงผลเวลา (เรียกใช้ผ่านคำสั่ง | thaitime)
# ==============================================================================
@app.template_filter('thaitime')
def thaitime_filter(dt):
    if not dt:
        return ""
    if isinstance(dt, str):
        try:
            dt = datetime.strptime(dt, '%Y-%m-%d %H:%M:%S')
        except ValueError:
            return dt
    return dt.strftime('%d/%m/%Y %H:%M')

# ==============================================================================
# ส่วนที่ 4: การตั้งค่าระบบความปลอดภัยการอัปโหลด (UPLOAD CONFIGURATION)
# หน้าที่: จำกัดขนาดไฟล์สูงสุดที่ผู้ใช้สามารถอัปโหลดเข้ามาในระบบได้ (ป้องกันเซิร์ฟเวอร์ทำงานหนัก)
# กำหนดไว้ที่: 16 MB
# ==============================================================================
app.config['MAX_CONTENT_LENGTH'] = 16 * 1024 * 1024 

# ==============================================================================
# ส่วนที่ 5: การลงทะเบียนระบบเส้นทาง (BLUEPRINT REGISTRATION)
# หน้าที่: นำเส้นทางของเว็บที่แยกเขียนไว้ในไฟล์ต่างๆ มาประกอบรวมกันเป็นแอปพลิเคชันเดียว
# - user_bp: จัดการระบบฝั่งผู้ใช้ทั่วไป (สมัคร, ล็อกอิน, แจ้งซ่อม)
# - admin_bp: จัดการระบบฝั่งผู้ดูแลระบบ (ดูภาพรวม, แบนผู้ใช้, จัดการสถานะ)
# - technician_bp: จัดการระบบฝั่งช่าง (ดูงานที่ได้รับมอบหมาย)
# ==============================================================================
app.register_blueprint(user_bp)
app.register_blueprint(admin_bp)
app.register_blueprint(technician_bp)

# ==============================================================================
# ส่วนที่ 6: คำสั่งรันเซิร์ฟเวอร์ (APPLICATION EXECUTION)
# หน้าที่: เปิดการทำงานของ Web Server ให้เข้าถึงได้ทุก IP ในวงแลนเดียวกัน (0.0.0.0)
# พอร์ตการทำงาน: 5002
# ==============================================================================
if __name__ == '__main__':
    app.run(host='0.0.0.0', port=5002, debug=True)